import assert from "node:assert/strict";
import {BAG_SIZE,belongings,inventoryAction,packedBoard} from "../public/walk-inventory.js";

const avatar={x:10000,y:6000,coast:{mode:"walk",board:true},bag:[]};
const store={kind:"surfboard",action:"storeBoard"},unpack={kind:"surfboard",action:"unpackBoard",index:0};
const apply=cmd=>inventoryAction(avatar,cmd,0);
assert.equal(apply(store),undefined);
assert.equal(avatar.coast.board,false);
assert.deepEqual(belongings(avatar).bag,[packedBoard]);
assert.ok(apply(store));
assert.ok(apply({...unpack,action:"hold",slot:"item",remaining:1}));
avatar.coast.mode="surf";
assert.ok(apply(unpack));
avatar.coast.mode="deck";
assert.equal(apply(unpack),undefined);
assert.ok(apply(unpack));
assert.equal(avatar.coast.board,true);
assert.deepEqual(avatar.bag,[]);
avatar.coast.mode="surf";
assert.ok(apply(store));
avatar.coast.mode="swim";
assert.equal(apply(store),undefined);
avatar.x=0;
assert.ok(apply(unpack));
avatar.x=10000;
assert.equal(apply(unpack),undefined);
avatar.coast.mode="walk";
avatar.bag=Array.from({length:BAG_SIZE},()=>({kind:"coffee",remaining:1,started:0}));
assert.ok(apply(store));
assert.equal(avatar.bag.length,BAG_SIZE);
assert.equal(avatar.coast.board,true);
console.log("Surfboard storage, re-equipping, duplicate commands, full bags and active rides passed.");
