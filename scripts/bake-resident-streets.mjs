function network(name,project,allowed,clear){
 const portals=[],nodes=[],edges=[],keys=new Map(),home=[],zones=new Map(),cells=new Map();
 const key=(x,z)=>x+","+z;
 function add(p,action=null,value=null){
  const x=Math.round(p.x*100)/100,z=Math.round(p.z*100)/100,k=key(x,z),point={x,z};
  if(!allowed(point))return -1;
  if(keys.has(k)){
   const i=keys.get(k);if(action){nodes[i][2]=action;nodes[i][3]=value;}return i;
  }
  const id=nodes.length,world=project(point);
  nodes.push([world.x,world.y,action,value]);keys.set(k,id);edges.push(new Set());
  const cx=Math.floor(x/32),cz=Math.floor(z/32);
  for(let a=cx-1;a<=cx+1;a++)for(let b=cz-1;b<=cz+1;b++)
   for(const other of cells.get(key(a,b))??[]){
    const distance=Math.hypot(x-other.x,z-other.z);
    if(distance<=34&&clear(point,other)&&clear(other,point)){edges[id].add(other.id);edges[other.id].add(id);}
   }
  const cell=key(cx,cz);if(!cells.has(cell))cells.set(cell,[]);cells.get(cell).push({...point,id});
  return id;
 }
 function line(points){
  for(let i=0;i<points.length;i++){
   const b=points[i],a=points[i-1];if(!a){add(b);continue;}
   const n=Math.ceil(Math.hypot(b.x-a.x,b.z-a.z)/24);
   for(let j=1;j<=n;j++)add({x:a.x+(b.x-a.x)*j/n,z:a.z+(b.z-a.z)*j/n});
  }
 }
 function site(p,action,value,spawn=true){
  const id=add(p,action,value);if(spawn&&id>=0)home.push(id);
 }
 function elevated(points,approach){
  // These stairs cross in plan. Connect only adjacent treads on the same flight.
  let previous=approach?add(approach):-1;
  for(const p of points){
   const k=[p.x,p.z,p.h].join(","),world=project(p);
   let i=keys.get(k);
   if(i==null){i=nodes.length;keys.set(k,i);nodes.push([world.x,world.y,"stairs",p.h]);edges.push(new Set());}
   if(previous>=0&&i!==previous){edges[previous].add(i);edges[i].add(previous);}
   previous=i;
  }
  home.push(previous);
  return previous;
 }
 function portal(a,b){
  const from=add(a),to=add(b);
  if(from<0||to<0||from===to)return;
  edges[from].add(to);edges[to].add(from);portals.push([from,to]);
 }
 function finish(spacing){
  for(let i=0;i<nodes.length;i++)if(edges[i].size){
   const [x,y]=nodes[i],zone=key(Math.floor(x/spacing),Math.floor(y/spacing));
   if(!zones.has(zone))zones.set(zone,i);
  }
  const homes=[...new Set([...home,...zones.values()])].filter(i=>edges[i].size);
  const list=nodes.map(([x,y,action,value],i)=>[x,y,[...edges[i]],...(action?[action,value]:[])]);
  const path=new URL("../public/"+name+"-resident-streets.js",import.meta.url);
  writeFileSync(path,"// Generated by scripts/bake-resident-streets.mjs. Coordinates use the player map.\nexport default "+JSON.stringify({homes,nodes:list,portals})+";\n");
  console.log(name,nodes.length,"nodes,",homes.length,"residents",Object.fromEntries([...new Set(nodes.map(n=>n[2]).filter(Boolean))].map(a=>[a,homes.filter(i=>nodes[i][2]===a).length])));
 }
 return {line,site,portal,elevated,finish};
}

